//! Real counters of the last solar frame, summed from the `ShadedStats` of
//! every draw (bodies, plasma arcs, attached effects and the spacecraft) and
//! from the view tests that decide which objects are drawn at all.

use crate::pipeline::ShadedStats;

/// One body of the scene in the last frame.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct BodyStats {
    /// Index in `SolarScene::bodies`.
    pub index: usize,
    /// Passed the view test and was drawn.
    pub visible: bool,
    /// Triangles submitted to the rasterizer (0 when culled).
    pub triangles: usize,
}

/// Counters of one frame. Objects are the bodies, the star's plasma loops
/// (one object for all arcs) and the spacecraft; the crown and the card
/// ring are counted as draws only.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct FrameStats {
    /// Objects that went through the view test.
    pub objects_tested: usize,
    /// Objects the view test rejected before any vertex was transformed.
    pub objects_culled: usize,
    /// Meshes sent to the rasterizer.
    pub draws: usize,
    /// Triangles of the drawn meshes.
    pub triangles_submitted: usize,
    /// Triangles dropped by the rasterizer: back faces, outside the screen
    /// or in front of the near plane.
    pub triangles_culled: usize,
    /// Fragments generated by the rasterizer.
    pub fragments: usize,
    /// Every body in scene order (cleared, never reallocated, per frame).
    pub per_body: Vec<BodyStats>,
}

impl FrameStats {
    /// Zeroes every counter and keeps the capacity of `per_body`.
    pub fn clear(&mut self) {
        let mut per_body = std::mem::take(&mut self.per_body);
        per_body.clear();
        *self = Self {
            per_body,
            ..Self::default()
        };
    }

    /// Records one view test.
    pub fn test(&mut self, visible: bool) {
        self.objects_tested += 1;
        self.objects_culled += !visible as usize;
    }

    /// Adds one draw.
    pub fn add(&mut self, s: &ShadedStats) {
        self.draws += 1;
        self.triangles_submitted += s.triangles_processed;
        self.triangles_culled += s.triangles_culled;
        self.fragments += s.fragments_generated;
    }

    /// Records body `index`: its view test and, when visible, its draw.
    pub fn body(&mut self, index: usize, visible: bool, s: &ShadedStats) {
        self.test(visible);
        if visible {
            self.add(s);
        }
        self.per_body.push(BodyStats {
            index,
            visible,
            triangles: if visible { s.triangles_processed } else { 0 },
        });
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn clear_keeps_capacity_and_zeroes_counters() {
        let mut stats = FrameStats::default();
        let s = ShadedStats {
            triangles_processed: 10,
            triangles_culled: 4,
            fragments_generated: 99,
            ..ShadedStats::default()
        };
        stats.body(0, true, &s);
        stats.body(1, false, &s);
        assert_eq!(
            (stats.objects_tested, stats.objects_culled, stats.draws),
            (2, 1, 1)
        );
        assert_eq!(stats.per_body[1].triangles, 0);
        let capacity = stats.per_body.capacity();
        stats.clear();
        assert_eq!(stats, FrameStats::default());
        assert_eq!(stats.per_body.capacity(), capacity);
    }
}
